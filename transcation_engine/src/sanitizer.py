import re


def sanitize_for_ai(description):

    if description is None:
        return ""

    text = str(description).upper().strip()

    # ======================================================
    # EMAIL ADDRESSES
    # ======================================================

    text = re.sub(
        r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b",
        " ",
        text,
        flags=re.IGNORECASE
    )

    # ======================================================
    # PHONE NUMBERS
    # ======================================================

    text = re.sub(
        r"(?:\+?1[-.\s]?)?"
        r"(?:\(?\d{3}\)?[-.\s]?)"
        r"\d{3}[-.\s]?\d{4}",
        " ",
        text
    )

    # ======================================================
    # LABELED ACCOUNT / CARD NUMBERS
    # ======================================================

    text = re.sub(
        r"\b(?:ACCT|ACCOUNT|CARD|A/C)"
        r"\s*(?:NO|NUMBER|NUM|#)?"
        r"\s*[:\-]?\s*"
        r"[A-Z0-9*X\-]{4,}\b",
        " ",
        text
    )

    # ======================================================
    # REFERENCE / AUTH / TRANSACTION IDs
    # ======================================================

    text = re.sub(
        r"\b(?:REF|REFERENCE|TXN|TRANSACTION|TRACE|AUTH)"
        r"\s*(?:NO|NUMBER|NUM|#)?"
        r"\s*[:\-]?\s*"
        r"[A-Z0-9\-]{4,}\b",
        " ",
        text
    )

    # ======================================================
    # LONG NUMBER SEQUENCES
    # ======================================================

    text = re.sub(
        r"\b\d{5,}\b",
        " ",
        text
    )

    # ======================================================
    # MASKED CARD NUMBERS
    #
    # XXXX1234
    # ****1234
    # ======================================================

    text = re.sub(
        r"\bX{2,}\d{2,4}\b",
        " ",
        text
    )

    text = re.sub(
        r"\*{2,}\d{2,4}",
        " ",
        text
    )

    # ======================================================
    # DATES
    # ======================================================

    text = re.sub(
        r"\b\d{1,2}[/-]\d{1,2}[/-]\d{2,4}\b",
        " ",
        text
    )

    text = re.sub(
        r"\b\d{4}[/-]\d{1,2}[/-]\d{1,2}\b",
        " ",
        text
    )

    # ======================================================
    # EXCESS PUNCTUATION
    # ======================================================

    text = re.sub(
        r"[^A-Z0-9&' ]",
        " ",
        text
    )

    # ======================================================
    # WHITESPACE
    # ======================================================

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()